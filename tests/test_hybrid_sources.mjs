import assert from 'node:assert/strict';
import { OFFICIAL_REFERENCE_PAGES, isOfficialRegulationUrl, officialSourceHints } from '../netlify/knowledge/official-references.mjs';
import { cleanFaqQuestion, queueFaqQuestion } from '../netlify/knowledge/faq-candidates.mjs';

assert.equal(OFFICIAL_REFERENCE_PAGES.length,2);
assert.ok(officialSourceHints('Apa perubahan PMK 62 Tahun 2023 untuk revisi DIPA?').some(s=>s.id==='PMK-41-2026'));
assert.ok(officialSourceHints('Berapa batas SBM tahun 2027?').some(s=>s.id==='PMK-54-2026'));
assert.ok(officialSourceHints('Halo yang tidak ada hubungannya').length===0);
assert.equal(isOfficialRegulationUrl('https://jdih.kemenkeu.go.id/dok/pmk-41-tahun-2026'),true);
assert.equal(isOfficialRegulationUrl('https://jdih.kemenkeu.go.id.evil.example/dok/pmk-41-tahun-2026'),false);
assert.equal(isOfficialRegulationUrl('http://jdih.kemenkeu.go.id/dok/pmk-41-tahun-2026'),false);
assert.equal(isOfficialRegulationUrl('https://user:password@jdih.kemenkeu.go.id/'),false);
assert.equal(cleanFaqQuestion('Bagaimana mekanisme revisi DIPA untuk belanja 52?'),'Bagaimana mekanisme revisi DIPA untuk belanja 52?');
assert.equal(cleanFaqQuestion('NIK 3171000000000000 perlu dipindah'),null);
assert.equal(cleanFaqQuestion('Silahkan hubungi namaku@example.com terkait DIPA'),null);
assert.equal(cleanFaqQuestion('Kontak 081234567891 untuk urusan revisi anggaran'),null);
assert.equal(cleanFaqQuestion('Kode OTP untuk admin anggaran'),null);
assert.equal(cleanFaqQuestion('Baca https://contoh.go.id/surat pribadi'),null);
let writes=0,key='',saved=null;
const store={async setJSON(k,payload,opts){writes++;key=k;saved=payload;assert.equal(opts.onlyIfNew,true);return {modified:true}}};
const q='Apakah akun belanja 52 dapat dialihkan menjadi 53 dengan revisi DIPA?';
assert.equal((await queueFaqQuestion(q,{consent:false,enabled:true,store})).accepted,false);
assert.equal((await queueFaqQuestion(q,{consent:true,enabled:false,store})).accepted,false);
assert.equal(writes,0);
const result=await queueFaqQuestion(q,{consent:true,enabled:true,store});
assert.equal(result.accepted,true);
assert.equal(result.created,true);
assert.equal(writes,1);
assert.ok(key.startsWith('pending/'));
assert.equal(saved.state,'PENDING_REVIEW');
assert.equal(saved.question,q);
assert.equal(saved.id.length,24);
assert.ok(!('history' in saved)&&!('ip' in saved)&&!('answer' in saved));
console.log('PASS: official JDIH pointers, spoofing resistance, opt-in, PII screening, human review gate.');
